//! `cargo xtask catalogue [--check]`: write `crates/igs-iec61850-mms-core/src/catalogue/generated/`
//! from the latest IEC code components (PROVENANCE.md D-002).
//!
//! The reading is strict: an unknown element, attribute value or type kind stops the generation, so
//! nothing of a namespace is dropped silently. The counts of the emitted entries are checked against
//! an independent count of the XML elements. No descriptive text is read: the light code components
//! carry none.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use roxmltree::{Document, Node};

const CC: &str = "docs/spec/iec61850-code-components";
const OUT: &str = "crates/igs-iec61850-mms-core/src/catalogue/generated";

/// One namespace file: module name, path under `CC`, standard it derives from.
struct Source {
    module: &'static str,
    path: &'static str,
    standard: &'static str,
}

const SOURCES: [Source; 4] = [
    Source {
        module: "ns_7_2",
        path: "IEC_61850-7-2.NSD.2007B6.Light/IEC_61850-7-2_2007B6.nsd",
        standard: "IEC 61850-7-2:2010+AMD1:2020",
    },
    Source {
        module: "ns_7_3",
        path: "IEC_61850-7-3.NSD.2007B6.Light/IEC_61850-7-3_2007B6.nsd",
        standard: "IEC 61850-7-3:2010+AMD1:2020",
    },
    Source {
        module: "ns_7_4",
        path: "IEC_61850-7-4.NSD.2007B6.Light/IEC_61850-7-4_2007B6.nsd",
        standard: "IEC 61850-7-4:2010+AMD1:2020",
    },
    Source {
        module: "ns_8_1",
        path: "IEC_61850-8-1.NSD.2003A4.Light/IEC_61850-8-1_2003A4.snsd",
        standard: "IEC 61850-8-1:2011+AMD1:2020",
    },
];
const APPNS: &str = "IEC_61850-8-1.NSD.2003A4.Light/ApplicableServiceNS.AppNS";

type Fail = String;

pub fn run(root: &Path, check: bool) -> Result<(), Fail> {
    let mut files: BTreeMap<String, String> = BTreeMap::new();
    let mut summary = String::new();
    let mut modules = Vec::new();
    for source in &SOURCES {
        let path = root.join(CC).join(source.path);
        let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
        let doc = Document::parse(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        let mut out = Emitter::default();
        let ns = doc.root_element();
        out.banner(source, ns)?;
        if source.module == "ns_8_1" {
            let app = root.join(CC).join(APPNS);
            let app_text =
                fs::read_to_string(&app).map_err(|e| format!("{}: {e}", app.display()))?;
            let app_doc =
                Document::parse(&app_text).map_err(|e| format!("{}: {e}", app.display()))?;
            out.service_namespace(ns, app_doc.root_element())?;
        } else {
            out.namespace(ns)?;
        }
        let _ = writeln!(summary, "{}: {}", source.module, out.counts_line());
        // One entry per line, not formatted: the modules are declared `#[rustfmt::skip]` in mod.rs.
        files.insert(format!("{}.rs", source.module), out.text.clone());
        modules.push(source);
    }
    files.insert("mod.rs".into(), format(&mod_rs(&modules))?);

    let dir = root.join(OUT);
    let mut stale = Vec::new();
    for (name, text) in &files {
        let path = dir.join(name);
        let current = fs::read_to_string(&path).unwrap_or_default();
        if current != *text {
            if check {
                stale.push(name.clone());
            } else {
                fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
                fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
            }
        }
    }
    print!("{summary}");
    if !stale.is_empty() {
        return Err(format!(
            "stale generated files: {}; run `cargo xtask catalogue`",
            stale.join(", ")
        ));
    }
    Ok(())
}

fn mod_rs(sources: &[&Source]) -> String {
    let mut s = String::from(
        "// Code generated by `cargo xtask catalogue`. Do not edit.\n//\n\
         // SPDX-License-Identifier: IEC-Code-Components-EULA\n\n\
         //! Data of the catalogue, generated from the IEC code components; see each module for its source\n\
         //! and the notices of the IEC Code Components EULA, and NOTICE at the root of the repository.\n\n",
    );
    for src in sources {
        let _ = writeln!(s, "#[rustfmt::skip]\npub mod {};", src.module);
    }
    s
}

fn format(source: &str) -> Result<String, Fail> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2021", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .map_err(|e| format!("rustfmt: {e}"))?;
    child
        .stdin
        .take()
        .ok_or("rustfmt: no stdin")?
        .write_all(source.as_bytes())
        .map_err(|e| format!("rustfmt: {e}"))?;
    let out = child
        .wait_with_output()
        .map_err(|e| format!("rustfmt: {e}"))?;
    if !out.status.success() {
        return Err("rustfmt failed on the generated code".into());
    }
    String::from_utf8(out.stdout).map_err(|e| e.to_string())
}

fn local(node: Node) -> String {
    node.tag_name().name().to_owned()
}

fn elements<'a, 'i>(node: Node<'a, 'i>) -> impl Iterator<Item = Node<'a, 'i>> {
    node.children().filter(|n| n.is_element())
}

fn attr<'a>(node: Node<'a, '_>, name: &str) -> Option<&'a str> {
    node.attribute(name)
}

fn need<'a>(node: Node<'a, '_>, name: &str) -> Result<&'a str, Fail> {
    node.attribute(name)
        .ok_or_else(|| format!("<{}> without {name}", local(node)))
}

fn flag(node: Node, name: &str) -> Result<bool, Fail> {
    match node.attribute(name) {
        None | Some("false") => Ok(false),
        Some("true") => Ok(true),
        Some(v) => Err(format!("<{}> {name}={v:?}", local(node))),
    }
}

fn kind(value: &str) -> Result<&'static str, Fail> {
    Ok(match value {
        "BASIC" => "TypeKind::Basic",
        "ENUMERATED" => "TypeKind::Enumerated",
        "CONSTRUCTED" => "TypeKind::Constructed",
        "SCSM" => "TypeKind::Scsm",
        "undefined" => "TypeKind::Undefined",
        other => return Err(format!("unknown typeKind {other:?}")),
    })
}

fn opt(value: Option<&str>) -> String {
    value.map_or_else(|| "None".to_owned(), |v| format!("Some({v:?})"))
}

/// Presence condition; absent means `M`, the default of NSD.xsd for `presCond` and `dsPresCond`.
fn presence(node: Node, cond: &str, args: &str) -> Result<String, Fail> {
    Ok(format!(
        "Presence {{ condition: {:?}, arguments: {} }}",
        attr(node, cond).unwrap_or("M"),
        opt(attr(node, args))
    ))
}

/// Type kind; absent means `BASIC`, the default of NSD.xsd for `typeKind`.
fn type_kind(node: Node) -> Result<&'static str, Fail> {
    kind(attr(node, "typeKind").unwrap_or("BASIC"))
}

#[derive(Default)]
struct Emitter {
    text: String,
    counts: BTreeMap<&'static str, (usize, usize)>,
}

impl Emitter {
    fn counts_line(&self) -> String {
        self.counts
            .iter()
            .map(|(k, (n, _))| format!("{k} {n}"))
            .collect::<Vec<_>>()
            .join(", ")
    }

    fn banner(&mut self, src: &Source, ns: Node) -> Result<(), Fail> {
        let id = need(ns, "id")?;
        let version = need(ns, "version")?;
        let revision = need(ns, "revision")?;
        let release = need(ns, "release")?;
        let notice = ns
            .descendants()
            .find(|n| n.has_tag_name((ns.tag_name().namespace().unwrap_or(""), "Notice")))
            .and_then(|n| n.text())
            .ok_or("namespace without copyright notice")?;
        let notice: Vec<&str> = notice.split_whitespace().collect();
        let _ = write!(
            self.text,
            "// Code generated by `cargo xtask catalogue` from {path}. Do not edit.\n//\n\
             // SPDX-License-Identifier: IEC-Code-Components-EULA\n//\n\
             // This code was derived from {std} within modifications permitted in the relevant IEC\n\
             // standard. Please reproduce this note if possible.\n//\n\
             // Copyright notice of the code component, as published by the IEC:\n",
            path = src.path,
            std = src.standard
        );
        let mut line = String::from("//");
        for word in notice {
            if line.len() + word.len() > 98 {
                let _ = writeln!(self.text, "{line}");
                line = String::from("//");
            }
            line.push(' ');
            line.push_str(word);
        }
        let _ = writeln!(self.text, "{line}");
        let _ = write!(
            self.text,
            "//\n// The conditions and disclaimer of the IEC Code Components EULA are in NOTICE.\n\n\
             //! Namespace {id}:{version}{revision}{release} (code component, light version).\n\n\
             use crate::catalogue::*;\n\n\
             /// Identity of the namespace.\n\
             pub static NAMESPACE: Namespace = Namespace {{ id: {id:?}, version: {version}, revision: '{revision}', release: {release} }};\n\n"
        );
        Ok(())
    }

    fn count(&mut self, what: &'static str, emitted: usize, expected: usize) -> Result<(), Fail> {
        if emitted != expected {
            return Err(format!("{what}: {emitted} emitted, {expected} in the file"));
        }
        self.counts.insert(what, (emitted, expected));
        Ok(())
    }

    fn namespace(&mut self, ns: Node) -> Result<(), Fail> {
        for child in elements(ns) {
            match child.tag_name().name() {
                "Copyright" | "Changes" | "DependsOn" | "Abbreviations" => {}
                "BasicTypes" => self.basic_types(child)?,
                "FunctionalConstraints" => self.functional_constraints(child)?,
                "PresenceConditions" => self.presence_conditions(child)?,
                "Enumerations" => self.enumerations(child)?,
                "ConstructedAttributes" => self.constructed(
                    child,
                    "CONSTRUCTED_ATTRIBUTES",
                    "ConstructedAttribute",
                    "constructed attributes",
                )?,
                "CDCs" => self.cdcs(child)?,
                "LNClasses" => self.ln_classes(child)?,
                other => return Err(format!("unknown section <{other}>")),
            }
        }
        Ok(())
    }

    fn service_namespace(&mut self, ns: Node, app: Node) -> Result<(), Fail> {
        for child in elements(ns) {
            match child.tag_name().name() {
                "Copyright" => {}
                "FunctionalConstraints" => self.functional_constraints(child)?,
                "PresenceConditions" => self.presence_conditions(child)?,
                "ServiceTypeRealizations" => self.constructed(
                    child,
                    "SERVICE_TYPE_REALIZATIONS",
                    "ServiceTypeRealization",
                    "service type realizations",
                )?,
                "ServiceConstructedAttributes" => self.constructed(
                    child,
                    "SERVICE_CONSTRUCTED_ATTRIBUTES",
                    "ServiceConstructedAttribute",
                    "service constructed attributes",
                )?,
                "ServiceCDCs" => self.service_cdcs(child)?,
                other => return Err(format!("unknown section <{other}>")),
            }
        }
        let mut s = String::from("/// Namespaces this service namespace applies to.\npub static APPLIES_TO: &[AppliesTo] = &[\n");
        let mut n = 0;
        for usage in elements(app).filter(|e| e.tag_name().name() == "ServiceNsUsage") {
            for to in elements(usage) {
                let _ = writeln!(
                    s,
                    "AppliesTo {{ id: {:?}, version: {}, revision: '{}', release: {} }},",
                    need(to, "id")?,
                    need(to, "version")?,
                    need(to, "revision")?,
                    need(to, "release")?
                );
                n += 1;
            }
        }
        s.push_str("];\n\n");
        self.text.push_str(&s);
        let expected = app
            .descendants()
            .filter(|e| e.tag_name().name() == "AppliesTo")
            .count();
        self.count("applies to", n, expected)
    }

    fn basic_types(&mut self, sec: Node) -> Result<(), Fail> {
        let mut s = String::from("/// Basic types.\npub static BASIC_TYPES: &[&str] = &[\n");
        let mut n = 0;
        for e in elements(sec) {
            let _ = writeln!(s, "{:?},", need(e, "name")?);
            n += 1;
        }
        s.push_str("];\n\n");
        self.text.push_str(&s);
        self.count(
            "basic types",
            n,
            sec.descendants()
                .filter(|e| e.tag_name().name() == "BasicType")
                .count(),
        )
    }

    fn functional_constraints(&mut self, sec: Node) -> Result<(), Fail> {
        let mut s = String::from("/// Functional constraints.\npub static FUNCTIONAL_CONSTRAINTS: &[FunctionalConstraint] = &[\n");
        let mut n = 0;
        for fc in elements(sec) {
            let (mut services, mut members) = (Vec::new(), Vec::new());
            for list in elements(fc) {
                for item in elements(list) {
                    match item.tag_name().name() {
                        "Service" => services.push(format!("{:?}", need(item, "name")?)),
                        "DataSetMemberOf" => members.push(format!("{:?}", need(item, "cb")?)),
                        other => {
                            return Err(format!("unknown <{other}> in a functional constraint"))
                        }
                    }
                }
            }
            let _ = writeln!(
                s,
                "FunctionalConstraint {{ abbreviation: {:?}, services: &[{}], data_set_member_of: &[{}] }},",
                need(fc, "abbreviation")?,
                services.join(", "),
                members.join(", ")
            );
            n += 1;
        }
        s.push_str("];\n\n");
        self.text.push_str(&s);
        let expected = sec
            .descendants()
            .filter(|e| e.tag_name().name() == "FunctionalConstraint")
            .count();
        self.count("functional constraints", n, expected)
    }

    fn presence_conditions(&mut self, sec: Node) -> Result<(), Fail> {
        let mut s = String::from(
            "/// Presence conditions.\npub static PRESENCE_CONDITIONS: &[PresenceCondition] = &[\n",
        );
        let mut n = 0;
        for e in elements(sec) {
            let _ = writeln!(
                s,
                "PresenceCondition {{ name: {:?}, argument: {} }},",
                need(e, "name")?,
                opt(attr(e, "argument"))
            );
            n += 1;
        }
        s.push_str("];\n\n");
        self.text.push_str(&s);
        let expected = sec
            .descendants()
            .filter(|e| e.tag_name().name() == "PresenceCondition")
            .count();
        self.count("presence conditions", n, expected)
    }

    fn enumerations(&mut self, sec: Node) -> Result<(), Fail> {
        let mut s =
            String::from("/// Enumerations.\npub static ENUMERATIONS: &[Enumeration] = &[\n");
        let (mut n, mut lits) = (0, 0);
        for e in elements(sec) {
            let _ = write!(
                s,
                "Enumeration {{ name: {:?}, literals: &[",
                need(e, "name")?
            );
            for lit in elements(e) {
                if lit.tag_name().name() != "Literal" {
                    return Err(format!(
                        "unknown <{}> in an enumeration",
                        lit.tag_name().name()
                    ));
                }
                let value: i32 = need(lit, "literalVal")?
                    .parse()
                    .map_err(|_| format!("literalVal of {:?}", attr(lit, "name")))?;
                let _ = write!(
                    s,
                    "Literal {{ name: {:?}, value: {value}, deprecated: {} }},",
                    need(lit, "name")?,
                    flag(lit, "deprecated")?
                );
                lits += 1;
            }
            s.push_str("] },\n");
            n += 1;
        }
        s.push_str("];\n\n");
        self.text.push_str(&s);
        self.count(
            "enumerations",
            n,
            sec.descendants()
                .filter(|e| e.tag_name().name() == "Enumeration")
                .count(),
        )?;
        self.count(
            "literals",
            lits,
            sec.descendants()
                .filter(|e| e.tag_name().name() == "Literal")
                .count(),
        )
    }

    fn sub_attribute(e: Node) -> Result<String, Fail> {
        if e.tag_name().name() != "SubDataAttribute" {
            return Err(format!(
                "unknown <{}> in a constructed attribute",
                e.tag_name().name()
            ));
        }
        Ok(format!(
            "SubDataAttribute {{ name: {:?}, type_name: {}, type_kind: {}, presence: {}, min_value: {}, max_value: {}, default_value: {} }},",
            need(e, "name")?,
            opt(attr(e, "type")),
            type_kind(e)?,
            presence(e, "presCond", "presCondArgs")?,
            opt(attr(e, "minValue")),
            opt(attr(e, "maxValue")),
            opt(attr(e, "defaultValue"))
        ))
    }

    fn constructed(
        &mut self,
        sec: Node,
        konst: &str,
        tag: &str,
        what: &'static str,
    ) -> Result<(), Fail> {
        let mut s = format!("/// {what}.\npub static {konst}: &[ConstructedAttribute] = &[\n");
        let mut n = 0;
        for ca in elements(sec) {
            if ca.tag_name().name() != tag {
                return Err(format!(
                    "unknown <{}> in <{}>",
                    ca.tag_name().name(),
                    sec.tag_name().name()
                ));
            }
            let _ = write!(
                s,
                "ConstructedAttribute {{ name: {:?}, type_kind_parameterized: {}, components: &[",
                need(ca, "name")?,
                flag(ca, "typeKindParameterized")?
            );
            for sub in elements(ca) {
                s.push_str(&Self::sub_attribute(sub)?);
            }
            s.push_str("] },\n");
            n += 1;
        }
        s.push_str("];\n\n");
        self.text.push_str(&s);
        self.count(
            what,
            n,
            sec.descendants()
                .filter(|e| e.tag_name().name() == tag)
                .count(),
        )
    }

    fn data_attribute(e: Node) -> Result<String, Fail> {
        Ok(format!(
            "DataAttribute {{ name: {:?}, fc: {:?}, type_name: {}, type_kind: {}, presence: {}, is_array: {}, size_attribute: {}, dchg: {}, qchg: {}, dupd: {}, default_value: {}, underlying_type: {}, underlying_type_kind: {} }},",
            need(e, "name")?,
            need(e, "fc")?,
            opt(attr(e, "type")),
            type_kind(e)?,
            presence(e, "presCond", "presCondArgs")?,
            flag(e, "isArray")?,
            opt(attr(e, "sizeAttribute")),
            flag(e, "dchg")?,
            flag(e, "qchg")?,
            flag(e, "dupd")?,
            opt(attr(e, "defaultValue")),
            opt(attr(e, "underlyingType")),
            match attr(e, "underlyingTypeKind") {
                Some(k) => format!("Some({})", kind(k)?),
                None => "None".into(),
            }
        ))
    }

    fn cdcs(&mut self, sec: Node) -> Result<(), Fail> {
        let mut s = String::from("/// Common data classes.\npub static CDCS: &[Cdc] = &[\n");
        let (mut n, mut das) = (0, 0);
        for cdc in elements(sec) {
            let (mut a, mut d, mut p) = (String::new(), String::new(), String::new());
            for e in elements(cdc) {
                match e.tag_name().name() {
                    "DataAttribute" => {
                        a.push_str(&Self::data_attribute(e)?);
                        das += 1;
                    }
                    "SubDataObject" => {
                        let _ = write!(
                            d,
                            "SubDataObject {{ name: {:?}, cdc: {:?}, presence: {}, is_array: {}, size_attribute: {} }},",
                            need(e, "name")?,
                            need(e, "type")?,
                            presence(e, "presCond", "presCondArgs")?,
                            flag(e, "isArray")?,
                            opt(attr(e, "sizeAttribute"))
                        );
                    }
                    "ServiceParameter" => {
                        let _ = write!(
                            p,
                            "ServiceParameter {{ name: {:?}, type_name: {}, type_kind: {} }},",
                            need(e, "name")?,
                            opt(attr(e, "type")),
                            type_kind(e)?
                        );
                    }
                    other => return Err(format!("unknown <{other}> in a CDC")),
                }
            }
            let _ = writeln!(
                s,
                "Cdc {{ name: {:?}, variant: {}, statistics: {}, deprecated: {}, enum_parameterized: {}, type_kind_parameterized: {}, data_attributes: &[{a}], sub_data_objects: &[{d}], service_parameters: &[{p}] }},",
                need(cdc, "name")?,
                opt(attr(cdc, "variant")),
                flag(cdc, "statistics")?,
                flag(cdc, "deprecated")?,
                flag(cdc, "enumParameterized")?,
                flag(cdc, "typeKindParameterized")?
            );
            n += 1;
        }
        s.push_str("];\n\n");
        self.text.push_str(&s);
        self.count(
            "CDCs",
            n,
            sec.descendants()
                .filter(|e| e.tag_name().name() == "CDC")
                .count(),
        )?;
        self.count(
            "data attributes",
            das,
            sec.descendants()
                .filter(|e| e.tag_name().name() == "DataAttribute")
                .count(),
        )
    }

    fn ln_classes(&mut self, sec: Node) -> Result<(), Fail> {
        let mut s = String::from("/// Logical-node classes, abstract and concrete, in namespace order.\npub static LN_CLASSES: &[LnClass] = &[\n");
        let (mut n, mut dos) = (0, 0);
        for ln in elements(sec) {
            let is_abstract = match ln.tag_name().name() {
                "AbstractLNClass" => true,
                "LNClass" => false,
                other => return Err(format!("unknown <{other}> in LNClasses")),
            };
            let _ = write!(
                s,
                "LnClass {{ name: {:?}, base: {}, is_abstract: {is_abstract}, can_have_log: {}, data_objects: &[",
                need(ln, "name")?,
                opt(attr(ln, "base")),
                flag(ln, "canHaveLOG")?
            );
            for d in elements(ln) {
                if d.tag_name().name() != "DataObject" {
                    return Err(format!(
                        "unknown <{}> in a logical-node class",
                        d.tag_name().name()
                    ));
                }
                let ds = presence(d, "dsPresCond", "dsPresCondArgs")?;
                let _ = write!(
                    s,
                    "DataObject {{ name: {:?}, cdc: {:?}, presence: {}, ds_presence: {ds}, transient: {}, deprecated: {}, underlying_type: {}, underlying_type_kind: {} }},",
                    need(d, "name")?,
                    need(d, "type")?,
                    presence(d, "presCond", "presCondArgs")?,
                    flag(d, "transient")?,
                    flag(d, "deprecated")?,
                    opt(attr(d, "underlyingType")),
                    match attr(d, "underlyingTypeKind") {
                        Some(k) => format!("Some({})", kind(k)?),
                        None => "None".into(),
                    }
                );
                dos += 1;
            }
            s.push_str("] },\n");
            n += 1;
        }
        s.push_str("];\n\n");
        self.text.push_str(&s);
        let expected = sec
            .descendants()
            .filter(|e| matches!(e.tag_name().name(), "LNClass" | "AbstractLNClass"))
            .count();
        self.count("logical-node classes", n, expected)?;
        self.count(
            "data objects",
            dos,
            sec.descendants()
                .filter(|e| e.tag_name().name() == "DataObject")
                .count(),
        )
    }

    fn service_cdcs(&mut self, sec: Node) -> Result<(), Fail> {
        let mut s = String::from(
            "/// 8-1 additions to CDCs.\npub static SERVICE_CDCS: &[ServiceCdc] = &[\n",
        );
        let mut n = 0;
        for c in elements(sec) {
            let _ = write!(
                s,
                "ServiceCdc {{ cdc: {:?}, attributes: &[",
                need(c, "cdc")?
            );
            for e in elements(c) {
                if e.tag_name().name() != "ServiceDataAttribute" {
                    return Err(format!(
                        "unknown <{}> in a service CDC",
                        e.tag_name().name()
                    ));
                }
                s.push_str(&Self::data_attribute(e)?);
            }
            s.push_str("] },\n");
            n += 1;
        }
        s.push_str("];\n\n");
        self.text.push_str(&s);
        self.count(
            "service CDCs",
            n,
            sec.descendants()
                .filter(|e| e.tag_name().name() == "ServiceCDC")
                .count(),
        )
    }
}

/// Root of the workspace (parent of `xtask/`).
pub fn workspace_root() -> PathBuf {
    let here = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    here.parent().map_or(here.clone(), Path::to_path_buf)
}
