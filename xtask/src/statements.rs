//! The capability statements (task V1; SCOPE-001 to SCOPE-003, AT-14).
//!
//! The source is `docs/capabilities.tsv`: one row per requirement, with its area, the item, its state, and the tests that cover it
//! (`path::function`). `cargo xtask statements --check` verifies that every named test exists (its file is there, and it defines the
//! function); `cargo xtask statements` also writes `docs/statements.md`, the statements of the capabilities by area. A row with no test
//! is a declared gap, and says so.

use std::fs;
use std::path::Path;

/// One row of the capability source.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Row {
    /// The requirement identifier (for example `CTL-002`).
    pub requirement: String,
    /// The area of the library (for example `controls`).
    pub area: String,
    /// What the row states.
    pub item: String,
    /// The state of the item: implemented, partial, or not implemented, with the decision.
    pub state: String,
    /// The tests that cover the item, as (file, function).
    pub tests: Vec<(String, String)>,
}

/// Parses the source: tab-separated, a header line starting with `#`, and five columns.
pub fn parse(source: &str) -> Result<Vec<Row>, String> {
    let mut rows = Vec::new();
    for (number, line) in source.lines().enumerate() {
        if line.trim().is_empty() || line.starts_with('#') {
            continue;
        }
        let columns: Vec<&str> = line.split('\t').collect();
        let [requirement, area, item, state, tests] = columns.as_slice() else {
            return Err(format!(
                "line {}: five tab-separated columns are expected",
                number.saturating_add(1)
            ));
        };
        let mut references = Vec::new();
        for reference in tests.split(',').map(str::trim).filter(|r| !r.is_empty()) {
            let Some((file, function)) = reference.split_once("::") else {
                return Err(format!(
                    "line {}: a test is written path::function, got {reference}",
                    number.saturating_add(1)
                ));
            };
            if function.is_empty() {
                return Err(format!(
                    "line {}: the function of {reference} is empty",
                    number.saturating_add(1)
                ));
            }
            references.push((file.to_string(), function.to_string()));
        }
        rows.push(Row {
            requirement: requirement.to_string(),
            area: area.to_string(),
            item: item.to_string(),
            state: state.to_string(),
            tests: references,
        });
    }
    Ok(rows)
}

/// Checks that every test of every row exists: its file is in the repository, and the file defines the function.
pub fn verify(root: &Path, rows: &[Row]) -> Result<(), String> {
    let mut missing = Vec::new();
    for row in rows {
        for (file, function) in &row.tests {
            let path = root.join(file);
            let text = match fs::read_to_string(&path) {
                Ok(text) => text,
                Err(_) => {
                    missing.push(format!(
                        "{}: the file {file} is not in the repository",
                        row.requirement
                    ));
                    continue;
                }
            };
            if !text.contains(&format!("fn {function}(")) {
                missing.push(format!(
                    "{}: {file} does not define {function}",
                    row.requirement
                ));
            }
        }
    }
    if missing.is_empty() {
        Ok(())
    } else {
        Err(missing.join("\n"))
    }
}

/// The statements as markdown, by area, in the order of the source.
pub fn render(rows: &[Row]) -> String {
    let mut out = String::from(
        "# Capabilities\n\n<!-- Generated by `cargo xtask statements` from docs/capabilities.tsv: do not edit. -->\n\n\
         Each row names the tests that cover it; `cargo xtask statements --check` verifies that they exist (AT-14).\n",
    );
    let mut areas: Vec<&str> = Vec::new();
    for row in rows {
        if !areas.contains(&row.area.as_str()) {
            areas.push(row.area.as_str());
        }
    }
    for area in areas {
        out.push_str(&format!(
            "\n## {area}\n\n| Requirement | Item | State | Tests |\n| --- | --- | --- | --- |\n"
        ));
        for row in rows.iter().filter(|row| row.area == area) {
            let tests = if row.tests.is_empty() {
                "none (declared gap)".to_string()
            } else {
                row.tests
                    .iter()
                    .map(|(file, function)| format!("`{function}` ({file})"))
                    .collect::<Vec<_>>()
                    .join("<br>")
            };
            out.push_str(&format!(
                "| {} | {} | {} | {} |\n",
                row.requirement, row.item, row.state, tests
            ));
        }
    }
    out
}

/// `cargo xtask statements [--check]`: verifies the source, and writes the statements unless `check` is set.
pub fn run(root: &Path, check: bool) -> Result<(), String> {
    let source = fs::read_to_string(root.join("docs/capabilities.tsv"))
        .map_err(|error| format!("docs/capabilities.tsv: {error}"))?;
    let rows = parse(&source)?;
    verify(root, &rows)?;
    if check {
        println!("statements: {} rows, every test exists", rows.len());
        return Ok(());
    }
    fs::write(root.join("docs/statements.md"), render(&rows))
        .map_err(|error| format!("docs/statements.md: {error}"))?;
    println!(
        "statements: {} rows written to docs/statements.md",
        rows.len()
    );
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_row_with_a_test_is_parsed_with_its_file_and_function() {
        let rows =
            parse("CTL-002\tcontrols\tOperate\tImplemented\tcrates/a.rs::one,crates/b.rs::two\n")
                .expect("parses");
        assert_eq!(
            rows[0].tests,
            [
                ("crates/a.rs".to_string(), "one".to_string()),
                ("crates/b.rs".to_string(), "two".to_string())
            ]
        );
    }

    #[test]
    fn a_row_without_five_columns_is_refused() {
        assert!(parse("CTL-002\tcontrols\tOperate\n").is_err());
    }

    #[test]
    fn a_test_without_its_function_is_refused() {
        assert!(parse("CTL-002\tcontrols\tOperate\tImplemented\tcrates/a.rs\n").is_err());
    }

    #[test]
    fn a_test_with_an_empty_function_is_refused() {
        assert!(
            parse("SCOPE-001\tconformance\tRows\tImplemented\tdocs/capabilities.tsv::\n").is_err()
        );
    }

    #[test]
    fn the_repository_source_parses_and_its_tests_exist() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
        let source = fs::read_to_string(root.join("docs/capabilities.tsv"))
            .expect("the source is in the repository");
        let rows = parse(&source).expect("the source parses");
        assert!(!rows.is_empty());
        verify(&root, &rows).expect("every test of the source exists");
    }

    #[test]
    fn a_row_without_a_test_is_a_declared_gap_in_the_statements() {
        let rows = parse("BRCB-001\treports\tHistory\tNot implemented\t\n").expect("parses");
        assert!(render(&rows).contains("none (declared gap)"));
    }
}
